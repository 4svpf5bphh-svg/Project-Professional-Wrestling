"use client";

import type { PlayerShowResultView, PlayerShowMatchView } from "../../../../dist/packages/application/src/results-view.js";
import type { PlayerWorldResultShowView, PlayerWorldResultMatchView } from "../../../../dist/packages/application/src/world-results-view.js";
import { showResultHighlights, type ShowResultHighlight } from "../../../../dist/packages/web-adapter/src/results-highlights.js";
import { reviewPlayerShow } from "../../../../dist/packages/web-adapter/src/results-review.js";
import styles from "./results.module.css";

type BroadcastShow = Pick<PlayerShowResultView, "eventId" | "runningOrder" | "crowdResponse" | "averageMatchRating" | "bestMatchRating" | "titleChangeCount" | "injuryCount" | "matchCount" | "segmentCount"> |
  Pick<PlayerWorldResultShowView, "eventId" | "runningOrder" | "crowdResponse" | "averageMatchRating" | "bestMatchRating" | "titleChangeCount" | "injuryCount" | "matchCount" | "segmentCount">;

function display(value: number): string {
  return new Intl.NumberFormat("en-GB", { maximumFractionDigits: 1 }).format(value);
}

export function MatchStarRating({ rating }: { rating: number }): React.JSX.Element {
  const safe = Number.isFinite(rating) ? Math.max(0, Math.min(5, rating)) : 0;
  return (
    <span className={styles.visualStarRating} role="img" aria-label={`${display(safe)} of 5 stars`}>
      <span className={styles.starGlyphs} aria-hidden="true">
        <span>★★★★★</span>
        <span className={styles.starFill} style={{ width: `${safe * 20}%` }}>★★★★★</span>
      </span>
      <strong>{display(safe)}</strong>
    </span>
  );
}

function iconFor(category: ShowResultHighlight["category"]): string {
  if (category === "CHAMPIONSHIP") return "🏆";
  if (category === "ARRIVAL") return "✦";
  if (category === "INJURY") return "✚";
  if (category === "FINISH") return "⚠";
  if (category === "MAIN_EVENT" || category === "MATCH") return "★";
  return "⚡";
}

export function segmentResultIcon(kind: string): string {
  if (["PROMO", "INTERVIEW", "CHALLENGE"].includes(kind)) return "🎤";
  if (kind === "VIDEO_PACKAGE") return "▶";
  if (kind === "CELEBRATION") return "★";
  if (kind === "LIVE_APPEARANCE") return "✦";
  if (["ATTACK", "POST_MATCH_ASSAULT", "RESCUE"].includes(kind)) return "⚡";
  if (kind.startsWith("STABLE_")) return "◆";
  return "◈";
}

type ReplayMatch = Pick<PlayerShowMatchView, "actualFinish" | "finishCheater" | "finishFallout"> | Pick<PlayerWorldResultMatchView, "actualFinish" | "finishCheater" | "finishFallout">;

/** All finishes below are explicit authoritative match results, never inferred
 * from booking intent or generated by a storytelling model. */
export function MatchFinishReplay({ match }: { match: ReplayMatch }): React.JSX.Element | null {
  const finish = match.actualFinish;
  if (finish === null) return null; // Historical unknown: no made-up fall.
  const story: Record<NonNullable<typeof finish>, [string, string, string]> = {
    CLEAN_PIN: ["CLEAN FINISH", "Pinfall — the referee counts three.", "standard"],
    SUBMISSION: ["SUBMISSION", "The match ends by submission.", "standard"],
    FLASH_PIN: ["FLASH PIN", "A sudden pinfall seals the victory.", "standard"],
    PROTECTED_FINISH: ["PROTECTED FINISH", "A protected or controversial ending. The precise mechanism was not recorded.", "standard"],
    DISQUALIFICATION: ["DISQUALIFIED!", "The referee catches the losing side cheating. The opposing side wins by DQ.", "cheating"],
    FOREIGN_OBJECT: ["DIRTY VICTORY", "A foreign object is used outside the referee's sight. The winning side steals the result.", "cheating"],
    INJURY_STOPPAGE: ["REFEREE STOPPAGE", "A serious injury forces the match to be stopped and the result changed.", "stoppage"],
  };
  const [heading, defaultDescription, tone] = story[finish];
  const actor = match.finishCheater?.name;
  const description = actor && finish === "DISQUALIFICATION"
    ? `${actor} is caught cheating and disqualified. The opposing side wins.`
    : actor && finish === "FOREIGN_OBJECT"
      ? `${actor} uses a foreign object while the referee is unsighted. The winning side steals the result.`
      : defaultDescription;
  return (
    <div className={`${styles.finishReplay} ${tone === "cheating" ? styles.finishCheating : tone === "stoppage" ? styles.finishStoppage : ""}`}>
      <span aria-hidden="true">{tone === "cheating" ? "⚠" : tone === "stoppage" ? "✚" : "◉"}</span>
      <div>
        <strong>{heading}</strong><small>{description}</small>
        {match.finishFallout?.reason === "HEEL_CHEATING_HEAT" ? (
          <small className={styles.finishHeat}>Heel heat landed · +{match.finishFallout.crowdAdjustment.toFixed(1)} show-flow crowd</small>
        ) : match.finishFallout?.reason === "FACE_CHEATING_BACKLASH" ? (
          <small className={styles.finishBacklash}>The babyface's cheating muddied the reaction · {match.finishFallout.crowdAdjustment.toFixed(1)} show-flow crowd</small>
        ) : null}
        {match.finishFallout && match.finishFallout.sameTrickRepeats > 0 ? (
          <small>The same trick has been used against these opponents recently. Its extra crowd lift is wearing thin.</small>
        ) : null}
        {match.finishFallout?.programmeLinked ? (
          <small>Programme-linked match · the next storyline beat remains the promoter's choice</small>
        ) : null}
      </div>
    </div>
  );
}

/** This is a presentation lens on already completed show records. */
export default function ShowBroadcast({ show }: { show: BroadcastShow }): React.JSX.Element {
  const moments = showResultHighlights(show);
  const lead = moments[0] ?? null;
  const otherMoments = moments.slice(1);
  const crowd = Number.isFinite(show.crowdResponse) ? show.crowdResponse : 0;
  const editorial = reviewPlayerShow(show);
  return (
    <section className={styles.broadcast} aria-label="Completed show highlights">
      <div className={styles.broadcastMasthead}>
        <span><span aria-hidden="true">◉</span> PPW · THE FINAL BELL</span>
        <span>THE SHOW REVIEW</span>
      </div>
      <div className={`${styles.broadcastEditorial} ${editorial.tone === "GREAT" ? styles.broadcastEditorialGreat : editorial.tone === "ROUGH" ? styles.broadcastEditorialRough : ""}`}>
        <small>THE VERDICT · {editorial.tone === "GREAT" ? "MUST SEE" : editorial.tone === "ROUGH" ? "ROUGH NIGHT" : editorial.tone === "GOOD" ? "WORTH WATCHING" : "MIXED FORTUNES"}</small>
        <h2>{editorial.headline}</h2>
        <p>{editorial.recap}</p>
        <em>{editorial.verdict}</em>
      </div>
      <div className={styles.broadcastNumbers}>
        <div className={styles.broadcastCrowd}>
          <span>CROWD RESPONSE</span>
          <strong>{display(show.crowdResponse)}<small> / 100</small></strong>
          <div className={styles.crowdRail} role="meter" aria-label="Final crowd response out of 100"
            aria-valuemin={0} aria-valuemax={100}
            aria-valuenow={Math.min(100, Math.max(0, Math.round(crowd)))}>
            <span style={{ width: `${Math.min(100, Math.max(0, crowd))}%` }} />
          </div>
        </div>
        <div className={styles.broadcastBest}>
          <span>BEST BOUT</span>
          <MatchStarRating rating={show.bestMatchRating} />
          <small>Show average ★ {display(show.averageMatchRating)}</small>
        </div>
      </div>
      {lead ? (
        <a className={`${styles.broadcastLead} ${lead.category === "CHAMPIONSHIP" ? styles.broadcastLeadTitle : lead.category === "INJURY" ? styles.broadcastLeadInjury : ""}`}
          href={`#show-${show.eventId}-slot-${lead.slotOrder}`}
          aria-label={`Read slot ${lead.slotOrder}: ${lead.headline}`}>
          <span className={styles.broadcastLeadIcon} aria-hidden="true">{iconFor(lead.category)}</span>
          <span className={styles.broadcastLeadContent}>
            <small>THE NIGHT'S HEADLINE · {lead.category.replaceAll("_", " ")} · SLOT {lead.slotOrder}</small>
            <strong>{lead.headline}</strong>
            <span>{lead.detail}</span>
            <em>See what happened <span aria-hidden="true">↗</span></em>
          </span>
        </a>
      ) : null}
      {otherMoments.length > 0 ? (
        <div className={styles.reelCards}>
          {otherMoments.map((moment) => (
            <a href={`#show-${show.eventId}-slot-${moment.slotOrder}`}
              className={`${styles.reelCard} ${moment.category === "CHAMPIONSHIP" ? styles.reelTitle : moment.category === "INJURY" ? styles.reelInjury : ""}`}
              key={moment.id}>
              <span className={styles.reelSymbol} aria-hidden="true">{iconFor(moment.category)}</span>
              <span className={styles.reelContents}>
                <small>{moment.category.replaceAll("_", " ")} · SLOT {moment.slotOrder}</small>
                <strong>{moment.headline}</strong>
                <span>{moment.detail}</span>
              </span>
              <span className={styles.reelArrow} aria-hidden="true">↗</span>
            </a>
          ))}
        </div>
      ) : !lead ? <p className={styles.reelEmpty}>Full completed card and crowd response below.</p> : null}
    </section>
  );
}
